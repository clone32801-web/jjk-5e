/**
 * Get direct Google Doc URL with heading anchor
 * @param {string} type - 'classes' | 'races' | 'techniques' | 'backgrounds' | 'feats' | 'rules' | 'equipment' | 'category'
 * @param {string} key - Specific entity ID / slug / name
 * @returns {string} Fully qualified Google Docs URL
 */
export function getGDocLink(type, key) {
  if (!type) return GDOC_BASE_URL;

  // If type is a direct heading ID (starts with 'h.')
  if (typeof type === 'string' && type.startsWith('h.')) {
    return `${GDOC_BASE_URL}#heading=${type}`;
  }

  const group = GDOC_SECTIONS[type];
  if (group) {
    if (key && group[key]) {
      return `${GDOC_BASE_URL}#heading=${group[key]}`;
    }
  }

  // Fallback to top category heading
  if (GDOC_SECTIONS.categories[type]) {
    return `${GDOC_BASE_URL}#heading=${GDOC_SECTIONS.categories[type]}`;
  }

  return GDOC_BASE_URL;
}
